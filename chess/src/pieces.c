static const char *const *const ART[7] = {NULL, ART_PAWN, ART_KNIGHT, ART_BISHOP, ART_ROOK, ART_QUEEN, ART_KING};

static bool filled(const char *const *art, int x, int y) {
    return x >= 0 && y >= 0 && x < PIECE_ART && y < PIECE_ART && art[y][x] != '.';
}

static SDL_Texture *make_texture(SDL_Renderer *r, const char *const *art, int color) {
    SDL_Surface *s = SDL_CreateSurface(PIECE_ART, PIECE_ART, SDL_PIXELFORMAT_RGBA32);
    if (!s) return NULL;
    SDL_ClearSurface(s, 0, 0, 0, 0);
    SDL_Color ink = tiny_color(TINY_INK), paper = tiny_color(TINY_PAPER);
    for (int y = 0; y < PIECE_ART; y++)
        for (int x = 0; x < PIECE_ART; x++) {
            bool on = filled(art, x, y), edge = false, halo = false;
            for (int dy = -1; dy <= 1; dy++)
                for (int dx = -1; dx <= 1; dx++) {
                    bool n = filled(art, x + dx, y + dy);
                    if (on && !n && (dx == 0 || dy == 0)) edge = true;
                    if (!on && n) halo = true;
                }
            SDL_Color c;
            if (on) {
                bool detail = art[y][x] == 'x';
                bool dark = edge || (color == BLACK) != detail;
                c = dark ? ink : paper;
            } else if (halo) {
                c = paper;
            } else {
                continue;
            }
            uint8_t *p = (uint8_t *)s->pixels + y * s->pitch + x * 4;
            p[0] = c.r;
            p[1] = c.g;
            p[2] = c.b;
            p[3] = 255;
        }
    SDL_Texture *t = SDL_CreateTextureFromSurface(r, s);
    SDL_DestroySurface(s);
    if (!t) return NULL;
    SDL_SetTextureBlendMode(t, SDL_BLENDMODE_BLEND);
    SDL_SetTextureScaleMode(t, SDL_SCALEMODE_NEAREST);
    return t;
}

static SDL_Texture *make_avatar(SDL_Renderer *r, const char *const *art) {
    SDL_Surface *s = SDL_CreateSurface(PIECE_ART, PIECE_ART, SDL_PIXELFORMAT_RGBA32);
    if (!s) return NULL;
    SDL_Color ink = tiny_color(TINY_INK), paper = tiny_color(TINY_PAPER);
    for (int y = 0; y < PIECE_ART; y++)
        for (int x = 0; x < PIECE_ART; x++) {
            SDL_Color c = art[y][x] == '#' ? ink : paper;
            uint8_t *p = (uint8_t *)s->pixels + y * s->pitch + x * 4;
            p[0] = c.r;
            p[1] = c.g;
            p[2] = c.b;
            p[3] = 255;
        }
    SDL_Texture *t = SDL_CreateTextureFromSurface(r, s);
    SDL_DestroySurface(s);
    if (t) SDL_SetTextureScaleMode(t, SDL_SCALEMODE_NEAREST);
    return t;
}

bool pieces_init(PieceSet *s, SDL_Renderer *r) {
    s->avatar[AVATAR_YOU] = make_avatar(r, ART_YOU);
    s->avatar[AVATAR_BOT] = make_avatar(r, ART_BOT);
    for (int c = 0; c < 2; c++)
        for (int t = PAWN; t <= KING; t++) {
            s->tex[c][t] = make_texture(r, ART[t], c);
            if (!s->tex[c][t]) {
                SDL_Log("piece texture: %s", SDL_GetError());
                pieces_free(s);
                return false;
            }
        }
    return true;
}

void pieces_free(PieceSet *s) {
    for (int i = 0; i < AVATAR_COUNT; i++) {
        if (s->avatar[i]) SDL_DestroyTexture(s->avatar[i]);
        s->avatar[i] = NULL;
    }
    for (int c = 0; c < 2; c++)
        for (int t = 0; t < 7; t++) {
            if (s->tex[c][t]) SDL_DestroyTexture(s->tex[c][t]);
            s->tex[c][t] = NULL;
        }
}

void pieces_draw(const PieceSet *s, SDL_Renderer *r, uint8_t piece, int x, int y, int size, uint8_t alpha) {
    if (!piece) return;
    SDL_Texture *t = s->tex[PCOLOR(piece)][PTYPE(piece)];
    if (!t) return;
    /* Whole-pixel scaling when it fills most of the square, else just fit it. */
    int k = size / PIECE_ART * PIECE_ART;
    if (k * 10 < size * 8) k = size * 9 / 10;
    SDL_FRect dst = {(float)(x + (size - k) / 2), (float)(y + (size - k) / 2), (float)k, (float)k};
    SDL_SetTextureAlphaMod(t, alpha);
    SDL_RenderTexture(r, t, NULL, &dst);
}

void pieces_draw_avatar(const PieceSet *s, SDL_Renderer *r, int which, int x, int y, int size) {
    if (which < 0 || which >= AVATAR_COUNT || !s->avatar[which]) return;
    SDL_FRect dst = {(float)x, (float)y, (float)size, (float)size};
    SDL_RenderTexture(r, s->avatar[which], NULL, &dst);
}
